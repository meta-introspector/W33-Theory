def frac(x):
    return x - (x.numerator // x.denominator)


def osc_counts(numbers, maxN):
    """number of bosonic oscillator states (multisets of creation operators) of each total N <= maxN"""
    cnt = Counter({F(0): 1})
    for w in numbers:
        new = Counter()
        for n, c in cnt.items():
            k = 0
            while n + k * w <= maxN:
                new[n + k * w] += c
                k += 1
        cnt = new
    return cnt


def _box(center, r, half):
    lo, hi = float(center) - r, float(center) + r
    if half:
        return [F(2 * k + 1, 2) for k in range(int(lo * 2) - 3, int(hi * 2) + 4) if lo - 1e-9 <= (2 * k + 1) / 2 <= hi + 1e-9]
    return [F(k) for k in range(int(lo) - 2, int(hi) + 3) if lo - 1e-9 <= k <= hi + 1e-9]


# ---------------------------------------------------------------- A. right movers
def so8_weights_near(shift, cap):
    """q in orbifolder's right-mover lattice (vector class: integer, odd sum; spinor: half-integer, even sum) with
    |q + shift|^2 <= cap"""
    r = float(cap) ** 0.5 + 1e-9
    for half in (False, True):
        for q in itertools.product(*[_box(-s, r, half) for s in shift]):
            if (sum(q) % 2 == 1) if not half else (sum(q) % 2 == 0):
                qs = [a + b for a, b in zip(q, shift)]
                n2 = sum(x * x for x in qs)
                if n2 <= cap:
                    yield qs, n2


def right_mover_levels(v, k):
    vk = [k * x for x in v]
    om = [frac(x) for x in vk[1:]]
    a_R = F(-1, 2) + sum(w * (1 - w) for w in om) / 2
    nums = [w for w in om if w] + [1 - w for w in om if w]
    osc = osc_counts(nums, F(1, 2))
    levels = Counter()
    for qs, n2 in so8_weights_near(vk, 2 * (F(1, 2) - a_R)):
        for N, c in osc.items():
            m = n2 / 2 + N + a_R
            if m <= 0:
                levels[(m, "scalar" if qs[0] == 0 else ("fermion" if qs[0].denominator == 2 else "vector"))] += c
    return a_R, levels


def right_mover_table(v):
    out = {}
    for k in range(6):
        a_R, lev = right_mover_levels(v, k)
        tach = {f"{m} {t}": c for (m, t), c in lev.items() if m < 0}
        out[str(k)] = dict(a_R=str(a_R), tachyonic=tach,
                           massless={t: c for (m, t), c in lev.items() if m == 0})
    return out


# ---------------------------------------------------------------- B. left movers, theta sector
def e8_near(V8, cap):
    r = float(cap) ** 0.5 + 1e-9
    for half in (False, True):
        for p in itertools.product(*[_box(-x, r, half) for x in V8]):
            if sum(p) % 2:
                continue
            s = sum((a + b) ** 2 for a, b in zip(p, V8))
            if s <= cap:
                yield list(p), s


def half_norm_counts(Vg, cap):
    a = Counter(s for _, s in e8_near(Vg[:8], 2 * cap))
    b = Counter(s for _, s in e8_near(Vg[8:], 2 * cap))
    out = Counter()
    for x, cx in a.items():
        for y, cy in b.items():
            if (x + y) / 2 <= cap:
                out[(x + y) / 2] += cx * cy
    return out


def theta_sector(V, W5):
    osc = osc_counts(OSC_THETA, F(3, 4))
    res = []
    for m in range(3):
        Vg = [v + m * w for v, w in zip(V, W5)]
        lv = half_norm_counts(Vg, F(3, 4))
        massless = sum(c * osc[F(3, 4) - h] for h, c in lv.items() if F(3, 4) - h in osc)
        tach = {f"{h}+N{F(7, 12) - h}": c * osc[F(7, 12) - h] for h, c in lv.items() if F(7, 12) - h in osc}
        excited = sum(c * osc[F(3, 4) - h] for h, c in lv.items() if h < F(3, 4) and F(3, 4) - h in osc)
        res.append(dict(m=m, massless_left_states=massless, massless_oscillator_excited=excited,
                        tachyonic_left_states=sum(tach.values()),
                        tachyonic_detail=tach, min_half_norm=str(min(lv)) if lv else None))
    return res


def witness(V, W5):
    for m in range(3):
        Vg = [v + m * w for v, w in zip(V, W5)]
        for h in (F(7, 12), F(5, 12), F(1, 4), F(1, 12)):
            A = list(e8_near(Vg[:8], 2 * h))
            B = {}
            for p, s in e8_near(Vg[8:], 2 * h):
                B.setdefault(s, p)
            for p, s in A:
                if 2 * h - s in B:
                    pp = p + B[2 * h - s]
                    return dict(m=m, p=[str(x) for x in pp], p_sh=[str(a + b) for a, b in zip(pp, Vg)],
                                half_norm=str(h), N_L=str(F(7, 12) - h))
    return None


def check_witness(V, W5, w):
    p = [F(x) for x in w["p"]]
    Vg = [v + w["m"] * x for v, x in zip(V, W5)]
    for blk in (p[:8], p[8:]):
        assert len({x.denominator for x in blk}) == 1 and blk[0].denominator in (1, 2) and sum(blk) % 2 == 0
    assert sum((a + b) ** 2 for a, b in zip(p, Vg)) / 2 == F(w["half_norm"])
    assert F(w["half_norm"]) + F(w["N_L"]) == F(7, 12) and F(w["N_L"]) in osc_counts(OSC_THETA, F(1, 2))
    return True


def modular_invariant(V, v):
    return (6 * (sum(x * x for x in V) - sum(x * x for x in v[1:]))) % 2 == 0


