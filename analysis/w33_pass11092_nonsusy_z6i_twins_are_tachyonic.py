def font_hernandez_control():
    V = [F(1, 6), F(1, 6), F(2, 3)] + [F(0)] * 5 + [F(0)] * 7 + [F(1)]
    W5 = [F(0)] * 16
    roots_kept = Counter()
    # gauge group check: E8 roots with p.V integer
    for blk, name in ((V[:8], "first E8"), (V[8:], "second E8")):
        n = 0
        for p, s in e8_near([F(0)] * 8, 2):
            if s == 2 and sum(a * b for a, b in zip(p, blk)).denominator == 1:
                n += 1
        roots_kept[name] = n
    ts = theta_sector(V, W5)
    return dict(shift=[str(x) for x in V], modular_invariant=modular_invariant(V, V_TWIN),
                roots_kept=dict(roots_kept), theta_sector=ts,
                tachyon_free=all(x["tachyonic_left_states"] == 0 for x in ts))


